const TEXT: Record<Locale, UiText> = { "pt-BR": PT, en: EN, es: ES, ja: JA };

export function ui(ctx: { locale?: Locale }): UiText {
  return TEXT[ctx.locale ?? MAIN_LOCALE];
}

/** URL prefix of a language: "" for Portuguese, "/en" for English. */
export function localePrefix(locale: Locale | undefined): string {
  return !locale || locale === MAIN_LOCALE ? "" : `/${locale}`;
}

/**
 * Keeps internal links in the visitor's language: "/taurus" becomes
 * "/en/taurus" on the English site. External links, anchors and files are
 * left alone.
 */
export function localHref(ctx: { locale?: Locale }, href: string): string {
  const prefix = localePrefix(ctx.locale);
  if (!prefix || !href.startsWith("/") || href.startsWith("//") || href.startsWith("/demo/") || href.startsWith("/arquivos/") || href.startsWith("/api/")) return href;
  if (href === prefix || href.startsWith(`${prefix}/`) || href.startsWith(`${prefix}#`)) return href;
  if (href === "/") return prefix;
  if (href.startsWith("/#")) return `${prefix}${href.slice(1)}`;
  return `${prefix}${href}`;
}

export function localeLabel(locale: Locale) {
  return LOCALE_LABELS[locale];
}
